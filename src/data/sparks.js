export function sparkOfTheDay(date = new Date()) {
  const key = date.toISOString().slice(0, 10)
  let h = 0
  for (let i = 0; i < key.length; i++) h = (h * 31 + key.charCodeAt(i)) | 0
  return sparks[Math.abs(h) % sparks.length]
}

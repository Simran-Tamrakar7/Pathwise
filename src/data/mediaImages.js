export function pickImage(pool, key) {
  const list = breakImagePools[pool] || breakImagePools.links
  let h = 0
  const s = String(key)
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) | 0
  return list[Math.abs(h) % list.length]
}
